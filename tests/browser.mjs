import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const ready = async()=>{
  await page.waitForFunction(()=>document.querySelector('.results-column')?.getAttribute('aria-busy')==='false');
};
const field=async(name,value)=>{
  await page.locator(`#${name}`).fill(String(value));
  await page.locator(`#${name}`).blur();
  await ready();
};
try {
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173');
  await ready();
  await page.locator('.comparison-row').first().waitFor();
  await page.screenshot({path:'/tmp/lucky-lab-desktop.png',fullPage:true});
  assert.equal(await page.title(),'Lucky Lab — Understand your odds');
  const expected=Number((await page.getByTestId('expected').innerText()).replace('prizes',''));
  assert.equal(expected,8.03);
  assert.equal(await page.locator('#others, #otherDraws').count(),0);
  assert.equal(await page.getByRole('checkbox',{name:'Limit total prizes'}).isChecked(),false);
  assert.equal(await page.locator('#prizes').count(),0);
  const individualChart = page.locator('#outcomes');
  const cumulativeChart = page.locator('#cumulative-outcomes');
  assert.equal(await page.locator('svg.outcome-chart').count(),2,'Individual and cumulative outcomes must have separate graphs');
  assert.equal(await individualChart.locator('svg path').count(),0,'Individual graph must contain bars without a cumulative line');
  await individualChart.getByRole('button',{name:/^Exactly 1 prizes?:/}).hover();
  assert.match(await individualChart.locator('.chart-tooltip').innerText(),/Exactly 1/);
  assert.doesNotMatch(await individualChart.locator('.chart-tooltip').innerText(),/More than/);
  await cumulativeChart.getByRole('button',{name:/^1 or more prizes:/}).hover();
  assert.match(await cumulativeChart.locator('.chart-tooltip').innerText(),/1 or more prizes/);
  assert.doesNotMatch(await page.locator('body').innerText(),/more than/i);
  assert.equal(await cumulativeChart.getByText('2 or more prizes',{exact:true}).count(),1);
  assert.ok((await cumulativeChart.locator('.cumulative-strip').innerText()).includes('99.95%'),'High cumulative chances must not round to certainty');
  console.log('PASS independent outcome and inclusive X-or-more graphs');
  const costNumber=async()=>Number((await page.getByTestId('cost-per-ticket').innerText()).replaceAll(',',''));
  const baseTicketCost=await costNumber();
  assert.ok(Math.abs(baseTicketCost - 200/(40*(1-.95**10))) < .0001);
  await field('donationCost',10);
  assert.ok(Math.abs(await costNumber() - 2000/(40*(1-.95**10))) < .0001);
  assert.equal(await page.getByTestId('total-cost').innerText(),'2,000.00');
  const costChart=page.locator('#cost-by-wins');
  const costCurve=costChart.getByRole('slider');
  await costCurve.focus();
  await page.keyboard.press('Home');
  assert.match(await costChart.locator('.chart-tooltip').innerText(),/1 prize · 2 tickets/);
  assert.match(await costChart.locator('.chart-tooltip').innerText(),/1,000.00/);
  await page.keyboard.press('ArrowRight');
  assert.match(await costChart.locator('.chart-tooltip').innerText(),/2 prizes · 4 tickets/);
  assert.match(await costChart.locator('.chart-tooltip').innerText(),/500.00/);
  await page.keyboard.press('End');
  assert.equal(await costCurve.getAttribute('aria-valuenow'),'20');
  assert.match(await costChart.locator('.chart-tooltip').innerText(),/50.00/);
  assert.match(await costChart.locator('.zero-win-note').innerText(),/No finite cost per ticket/);
  console.log('PASS donation input, theoretical cost and keyboard cost-by-wins graph');
  await field('probability',100);
  assert.equal((await page.getByTestId('expected').innerText()).replace('prizes',''),'20.00');
  await page.getByRole('checkbox',{name:'Limit total prizes'}).check();
  await ready();
  await field('prizes',3);
  assert.equal((await page.getByTestId('expected').innerText()).replace('prizes',''),'3.00');
  assert.equal(await page.getByTestId('at-least-one').innerText(),'100.00%');
  await cumulativeChart.getByRole('button',{name:'3 or more prizes: 100.00%'}).hover();
  assert.match(await cumulativeChart.locator('.chart-tooltip').innerText(),/100.00%/);
  assert.equal(await page.getByTestId('expected-tickets').innerText(),'6.00');
  assert.ok(Math.abs(await costNumber() - 2000/6) < .0001);
  await costCurve.focus();
  await page.keyboard.press('End');
  assert.equal(await costCurve.getAttribute('aria-valuenow'),'3');
  assert.match(await costChart.locator('.chart-tooltip').innerText(),/333.3333/);
  await field('prizes',0);
  assert.equal(await costCurve.count(),0);
  assert.ok(await costChart.locator('.cost-curve-empty').isVisible());
  assert.equal((await page.getByTestId('expected').innerText()).replace('prizes',''),'0.00');
  assert.equal(await page.getByTestId('cost-per-ticket').innerText(),'—');
  assert.ok(await page.getByText('No tickets expected',{exact:true}).isVisible());
  await page.getByRole('checkbox',{name:'Limit total prizes'}).uncheck();
  await ready();
  assert.equal((await page.getByTestId('expected').innerText()).replace('prizes',''),'20.00');
  await field('probability',0);
  assert.equal(await page.getByTestId('at-least-one').innerText(),'0.00%');
  console.log('PASS certain probability, optional cap, cap disable and zero probability');
  await page.getByRole('button',{name:'Reset to example',exact:true}).click();
  await ready();
  assert.equal(await page.locator('#donationCost').inputValue(),'1');
  assert.equal(await page.getByRole('button',{name:'Run simulation',exact:true}).count(),0);
  assert.doesNotMatch(await page.locator('body').innerText(),/10,000 rounds|simulat|confidence interval/i);
  await field('probability',6);
  await field('probability',5);
  assert.equal((await page.getByTestId('expected').innerText()).replace('prizes',''),'8.03');
  assert.equal(await page.getByTestId('cost-per-ticket').innerText(),baseTicketCost.toLocaleString(undefined,{minimumFractionDigits:2,maximumFractionDigits:4}));
  console.log('PASS deterministic calculation and removal of simulation controls');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export results',exact:true}).click();
  const download=await downloadPromise;
  await download.saveAs('/tmp/lucky-lab-results.csv');
  const csv=await fs.readFile('/tmp/lucky-lab-results.csv','utf8');
  assert.match(csv,/probability_x_or_more/);
  assert.match(csv,/accounts,20/);
  assert.match(csv,/limitPrizes,false/);
  assert.match(csv,/donation_cost,1/);
  assert.match(csv,/tickets_per_prize,2/);
  assert.match(csv,/theoretical_cost_per_ticket/);
  const rows=csv.split('\n');
  assert.ok(rows.includes('prizes,probability,probability_x_or_more,tickets,cost_per_ticket'));
  const distribution=rows.slice(rows.indexOf('prizes,probability,probability_x_or_more,tickets,cost_per_ticket')+1).map(row=>row.split(',').map(Number));
  for(let i=0;i<distribution.length;i++){
    const expectedTail=distribution.slice(i).reduce((sum,row)=>sum+row[1],0);
    assert.ok(Math.abs(distribution[i][2]-expectedTail)<1e-10,'CSV cumulative probability must include X itself');
  }
  assert.doesNotMatch(csv,/others|otherDraws|qualifying|rounds|seed/);
  assert.equal(distribution.length,21);
  assert.match(rows.at(-21),/^0,[^,]+,1,0,$/);
  assert.equal(distribution[1][3],2);
  assert.equal(distribution[1][4],100);
  assert.equal(distribution[2][4],50);
  console.log('PASS CSV download with scenario and cumulative probabilities');
  await page.getByRole('button',{name:'How it works'}).click();
  await page.locator('dialog[open]').waitFor();
  assert.match(await page.locator('dialog').innerText(),/binomial distribution/i);
  assert.doesNotMatch(await page.locator('dialog').innerText(),/simulat|rounds/i);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog').count(),0);
  await page.locator('.comparison-row').first().click();
  await ready();
  const accounts=Number(await page.locator('#accounts').inputValue());
  const draws=Number(await page.locator('#draws').inputValue());
  assert.equal(accounts*draws,200);
  console.log('PASS model dialog and equal-budget comparison');
  await page.getByRole('button',{name:'Reset to example',exact:true}).click();
  await ready();
  await page.locator('#accounts').fill('');
  await page.locator('#accounts').blur();
  assert.equal(await page.locator('#accounts').inputValue(),'20');
  await page.locator('#accounts').fill('2001');
  await page.locator('#accounts').blur();
  assert.equal(await page.locator('#accounts').inputValue(),'20');
  await page.locator('#accounts').fill('1.5');
  await page.locator('#accounts').blur();
  assert.equal(await page.locator('#accounts').inputValue(),'20');
  await field('donationCost',0);
  assert.equal(await page.getByTestId('cost-per-ticket').innerText(),'0.00');
  await costCurve.focus();
  await page.keyboard.press('Home');
  assert.match(await costChart.locator('.chart-tooltip').innerText(),/Cost per ticket\s*0.00/);
  await field('donationCost',1);
  console.log('PASS invalid numeric input recovery and zero donation cost');
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>{
    const labels=[...document.querySelectorAll('#outcomes .x-label')].map(el=>el.getBoundingClientRect());
    return labels.every((rect,i)=>i===0 || labels[i-1].right+2<=rect.left);
  });
  await page.screenshot({path:'/tmp/lucky-lab-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile layout overflows');
  await page.locator('#probability').fill('10');
  await ready();
  assert.ok(await page.locator('#outcomes .outcome-chart').isVisible());
  assert.ok(await page.locator('#cumulative-outcomes .outcome-chart').isVisible());
  console.log('PASS mobile layout and interactions');
  const touchPage = await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
  touchPage.on('pageerror', e=>errors.push(e.message));
  await touchPage.goto(process.env.APP_URL || 'http://127.0.0.1:5173');
  await touchPage.waitForFunction(()=>document.querySelector('.results-column')?.getAttribute('aria-busy')==='false');
  for (const chartId of ['outcomes','cumulative-outcomes']) {
    const chart=touchPage.locator(`#${chartId}`);
    await chart.locator('rect[role="button"]').first().tap();
    assert.ok(await chart.locator('.chart-tooltip').isVisible(),'First touch must show a tooltip in each graph');
    const secondPoint=chart.locator('rect[role="button"]').nth(1);
    const label=await secondPoint.getAttribute('aria-label');
    await secondPoint.tap();
    assert.ok((await chart.locator('.chart-tooltip').innerText()).includes(label.split(':')[0]));
  }
  const touchCost=touchPage.locator('#cost-by-wins');
  const touchCurve=touchCost.getByRole('slider');
  await touchCurve.tap({position:{x:60,y:100}});
  assert.ok(await touchCost.locator('.chart-tooltip').isVisible());
  const firstCostWin=Number(await touchCurve.getAttribute('aria-valuenow'));
  await touchCurve.tap({position:{x:220,y:100}});
  assert.ok(Number(await touchCurve.getAttribute('aria-valuenow'))>firstCostWin,'Touch must select different cost outcomes');
  assert.match(await touchCost.locator('.chart-tooltip').innerText(),/Cost per ticket/);
  await touchPage.close();
  console.log('PASS first-tap and subsequent-tap graph tooltips');
  await page.route('**/*calculation.worker*', route=>route.abort());
  await field('probability',0);
  await page.getByRole('alert').waitFor();
  assert.equal((await page.getByTestId('expected').innerText()).replace('prizes','').trim(),'—','Failed new scenario must not display stale results');
  assert.ok(await page.getByRole('button',{name:'Export results',exact:true}).isDisabled(),'Failed new scenario must not export stale results');
  await page.unroute('**/*calculation.worker*');
  await page.getByRole('button',{name:'Reset to example',exact:true}).click();
  await page.waitForFunction(()=>Number(document.querySelector('[data-testid="expected"]').innerText.replace('prizes',''))>7.9);
  await ready();
  assert.ok(Number((await page.getByTestId('expected').innerText()).replace('prizes',''))>7.9);
  console.log('PASS failed worker invalidates results and reset recovers');
  assert.deepEqual(errors,[]);
  console.log('PASS no browser runtime errors');
} finally {await browser.close();}
